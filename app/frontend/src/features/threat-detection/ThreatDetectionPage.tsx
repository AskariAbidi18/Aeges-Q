import { useState } from 'react';
import { AlertTriangle, Play, FileInput } from 'lucide-react';
import { PageHeader } from '../../components/layout/PageHeader';
import { SectionCard, StatusBadge, EmptyState, Term } from '../../components/ui/ui';
import { idsMetrics, sampleFlow } from '../../mocks/fixtures';
import { f4, pct } from '../../lib/format';
type F = typeof sampleFlow;
const empty: F = { duration: '', spkts: '', dpkts: '', sbytes: '', dbytes: '', rate: '', sttl: '', proto: 'tcp' };
const fields: [keyof F, string, string][] = [['duration', 'Duration (s)', 'dur'], ['spkts', 'Source packets', 'spkts'], ['dpkts', 'Destination packets', 'dpkts'], ['sbytes', 'Source bytes', 'sbytes'], ['dbytes', 'Destination bytes', 'dbytes'], ['rate', 'Rate (pkts/s)', 'rate'], ['sttl', 'Source TTL', 'sttl']];
// Deterministic toy scoring for UI illustration only. Not a model.
const score = (f: F) => { const n = (k: keyof F) => Number(f[k]); const r = 0.1 * Math.log10(1 + n('rate')) + 0.06 * Math.log10(1 + n('sbytes')) + 0.05 * Math.log10(1 + n('spkts')) + (n('sttl') < 64 ? 0.12 : 0) + (f.proto === 'udp' ? 0.05 : 0); return Math.min(0.99, Math.max(0.01, r)); };
export function ThreatDetectionPage() {
  const [form, setForm] = useState<F>(empty);
  const [errors, setErrors] = useState<Partial<Record<keyof F, string>>>({});
  const [state, setState] = useState<'idle' | 'loading' | 'result'>('idle');
  const [risk, setRisk] = useState(0);
  const run = () => {
    const e: typeof errors = {};
    fields.forEach(([k, l]) => { const v = form[k]; if (v.trim() === '' || Number.isNaN(Number(v)) || Number(v) < 0) e[k] = `${l}: enter a number ≥ 0`; });
    setErrors(e); if (Object.keys(e).length) { setState('idle'); return; }
    setState('loading'); setTimeout(() => { setRisk(score(form)); setState('result'); }, 500);
  };
  const cls = risk >= 0.5 ? 'Attack-like (simulated)' : 'Normal-like (simulated)';
  return (
    <>
      <PageHeader title="Threat detection">Illustrates how a classical IDS result could be presented. Nothing here calls the trained model.</PageHeader>
      <div className="grid g2">
        <SectionCard title="Flow features" label={<StatusBadge kind="demo" text="DEMO INPUTS" />}>
          <div className="fg">{fields.map(([k, l, t]) => (
            <div className="field" key={k}><label htmlFor={k}>{l} <span className="mono">({t})</span></label>
              <input id={k} inputMode="decimal" value={form[k]} aria-invalid={!!errors[k]} aria-describedby={errors[k] ? `${k}-e` : undefined} onChange={e => setForm({ ...form, [k]: e.target.value })} />
              {errors[k] && <span className="err" id={`${k}-e`}>{errors[k]}</span>}</div>))}
            <div className="field"><label htmlFor="proto">Protocol</label><select id="proto" value={form.proto} onChange={e => setForm({ ...form, proto: e.target.value })}><option>tcp</option><option>udp</option><option>icmp</option></select></div></div>
          <div className="actions"><button className="btn sec" onClick={() => { setForm(sampleFlow); setErrors({}); setState('idle'); }}><FileInput size={15} />Load sample</button>
            <button className="btn" onClick={run} disabled={state === 'loading'}><Play size={15} />{state === 'loading' ? 'Running…' : 'Run demo prediction'}</button></div>
          <p className="warn"><AlertTriangle size={16} style={{ flex: 'none' }} />Demonstration only. This does not inspect live network traffic or call the trained model.</p>
        </SectionCard>
        <SectionCard title="Result" label={<StatusBadge kind="simulated" />}>
          {state === 'idle' && <EmptyState>Load the sample or enter values, then run the demo prediction.</EmptyState>}
          {state === 'loading' && <EmptyState>Computing local simulated result…</EmptyState>}
          {state === 'result' && <div aria-live="polite">
            <div className="metric"><div className="l">Predicted class</div><div className="v">{cls}</div></div>
            <div className="row"><span><Term t="Risk score" tip="Illustrative value from a toy local formula, not a model output" /></span><b className="mono">{risk.toFixed(2)}</b></div>
            <div className="row"><span>Risk summary</span><b>{risk >= 0.7 ? 'High' : risk >= 0.5 ? 'Elevated' : 'Low'}</b></div>
            <p className="mu" style={{ fontSize: 12, marginTop: 8 }}>SIMULATED INTERACTION: generated by a fixed local formula from the entered values. It is not a real model prediction.</p></div>}
        </SectionCard>
      </div>
      <div style={{ marginTop: 16 }}><SectionCard title="Classical IDS held-out metrics" label={<StatusBadge kind="historical" text="OFFLINE BENCHMARK — NOT LIVE PERFORMANCE" />}>
        <div className="grid g3">{([['Accuracy', idsMetrics.accuracy], ['Precision', idsMetrics.precision], ['Recall', idsMetrics.recall], ['F1', idsMetrics.f1], ['ROC-AUC', idsMetrics.rocAuc]] as const).map(([l, v]) => <div key={l} className="row"><span>{l}</span><b className="mono">{f4(v)}</b></div>)}
          <div className="row"><span>Normal-only FPR</span><b className="mono">≈ {pct(idsMetrics.normalFpr)}</b></div></div>
      </SectionCard></div>
    </>
  );
}
